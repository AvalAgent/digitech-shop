// ─────────────────────────────────────────────────────────
// Stock plan: which products are fully sold out (every variant 0).
// ─────────────────────────────────────────────────────────
const SOLD_OUT = new Set(["airpods-max", "galaxy-watch-6-classic"]);
const ZERO_SHARE = 0.1; // ~10% of all variants at stock 0 (sold-out products included)

function storageLabel(gb, cat) {
  if (!gb) return "";
  const size = gb >= 1024 ? `${toFa(gb / 1024)} ترابایت` : `${toFa(gb)} گیگابایت`;
  return cat === "laptop" ? `${size} SSD` : size;
}

// round to a shop-realistic step: cheap items to 10k, mid to 50k, big to 100k
function stepFor(price) {
  return price < 2000000 ? 10000 : price < 10000000 ? 50000 : 100000;
}

function legacyIndex(model) {
  // map "<gb>|<colourSlug or *>" → { id, sku } of the old synthetic variant
  const out = new Map();
  if (!model.legacy) return { map: out, count: 0 };
  const [kind, colorCount] = model.legacy;
  const cols = LEGACY_COLORS.slice(0, colorCount);
  let v = 0;
  for (const gb of LEGACY_STORAGE[kind]) {
    for (const col of cols) {
      v++;
      const parts = [model.slug];
      if (gb) parts.push(`${gb}gb`);
      if (cols.length > 1) parts.push(col);
      out.set(`${gb}|${cols.length > 1 ? col : "*"}`, { id: `${model.slug}-v${v}`, sku: parts.join("-") });
    }
  }
  return { map: out, count: v };
}

const out = [];
let modelIdx = 0;
let keptVariants = 0;
for (const model of models) {
  modelIdx++;
  const { map: legacy, count: legacyCount } = legacyIndex(model);
  const storages = model.storages ?? [[0, model.price]];
  const multiColor = model.colors.length > 1;

  const variants = [];
  let next = legacyCount;
  for (const [gb, basePrice] of storages) {
    model.colors.forEach(([colorFa, colorSlug], ci) => {
      const step = stepFor(basePrice);
      // most colours cost the same; the occasional one sits a step above or below
      const jitter = ci === 0 ? 0 : Math.round((rnd() - 0.5) * 2.4) * step;
      const price = Math.round((basePrice + jitter) / step) * step;

      const hit = legacy.get(`${gb}|${colorSlug}`) ?? (ci === 0 ? legacy.get(`${gb}|*`) : undefined);
      let id, sku;
      if (hit) {
        ({ id, sku } = hit);
        keptVariants++;
      } else {
        next++;
        id = `${model.slug}-v${next}`;
        const parts = [model.slug];
        if (gb) parts.push(`${gb}gb`);
        if (multiColor) parts.push(colorSlug);
        sku = parts.join("-");
      }
      // realistic shelf: mostly a handful, sometimes just one or two left
      const r = rnd();
      const stock = r < 0.15 ? between(1, 2) : r < 0.75 ? between(3, 9) : between(10, 24);
      variants.push({
        id,
        sku,
        ...(gb ? { storage: storageLabel(gb, model.cat) } : {}),
        ...(multiColor ? { color: colorFa } : {}),
        priceIRR: price,
        stock,
      });
    });
  }

  const images = existsSync(join(IMG_DIR, `${model.slug}.jpg`)) ? [`/products/${model.slug}.jpg`] : [];

  out.push({
    id: `p${String(modelIdx).padStart(3, "0")}`,
    slug: model.slug,
    name: model.name,
    brand: model.brand,
    category: model.cat,
    priceIRR: 0,
    rating: Math.round((3.9 + rnd() * 1.0) * 10) / 10,
    stock: 0,
    specs: { ...model.specs },
    description: model.desc,
    images,
    variants,
  });
}

// ── out-of-stock pass (deterministic) ────────────────────
for (const p of out) if (SOLD_OUT.has(p.slug)) for (const v of p.variants) v.stock = 0;
const totalVariants = out.reduce((s, p) => s + p.variants.length, 0);
const target = Math.round(totalVariants * ZERO_SHARE);
let zeroed = out.reduce((s, p) => s + p.variants.filter((v) => v.stock === 0).length, 0);
const pool = out
  .filter((p) => !SOLD_OUT.has(p.slug) && p.variants.length > 1)
  .flatMap((p) => p.variants.map((v) => ({ p, v })));
for (let i = pool.length - 1; i > 0; i--) {
  const j = Math.floor(rnd() * (i + 1));
  [pool[i], pool[j]] = [pool[j], pool[i]];
}
for (const { p, v } of pool) {
  if (zeroed >= target) break;
  // never sell out a product that is not on the SOLD_OUT list
  if (p.variants.filter((x) => x.stock > 0).length <= 1) continue;
  v.stock = 0;
  zeroed++;
}

for (const p of out) {
  p.priceIRR = Math.min(...p.variants.map((x) => x.priceIRR));
  p.stock = p.variants.reduce((s, x) => s + x.stock, 0);
}

// interleave categories round-robin so the "all" listing shows a mix,
// not 17 phones in a row
const buckets = new Map();
for (const p of out) {
  if (!buckets.has(p.category)) buckets.set(p.category, []);
  buckets.get(p.category).push(p);
}
const interleaved = [];
const lists = [...buckets.values()];
for (let i = 0; interleaved.length < out.length; i++) {
  for (const list of lists) if (list[i]) interleaved.push(list[i]);
}

writeFileSync(join(__dirname, "../src/data/catalog.json"), JSON.stringify(interleaved, null, 2) + "\n");

const byCat = interleaved.reduce((a, p) => ((a[p.category] = (a[p.category] || 0) + 1), a), {});
const soldOut = interleaved.filter((p) => p.stock === 0).map((p) => p.slug);
const noImage = interleaved.filter((p) => p.images.length === 0).map((p) => p.slug);
console.log(`generated ${interleaved.length} products, ${totalVariants} variants`, byCat);
console.log(`stock 0: ${zeroed} variants (${((zeroed / totalVariants) * 100).toFixed(1)}%), sold-out products: ${soldOut.join(", ")}`);
console.log(`kept legacy variant ids: ${keptVariants}`);
if (noImage.length) console.log(`no image: ${noImage.join(", ")}`);
